#!/usr/bin/env python3
"""
Converts a rectangular region of an image into a depth-mapped OBJ mesh,
using HSL lightness as the Z (depth) value.

Port of the Digital Epigraphy and Archaeology project's PHP depthmap-to-OBJ
script (www.digitalepigraphy.org), adapted to read a sub-region of the
source image and to use HSL lightness instead of luma-weighted grey.
"""

import argparse

import numpy as np
from PIL import Image


def rgb_to_hsl_lightness(rgb: np.ndarray) -> np.ndarray:
    """HSL lightness (0..1) for an (H, W, 3) uint8 RGB array."""
    arr = rgb.astype(np.float64) / 255.0
    cmax = arr.max(axis=2)
    cmin = arr.min(axis=2)
    return (cmax + cmin) / 2.0


def build_mesh(lightness: np.ndarray, dpm: float, depth_range: float, base_thickness: float):
    """Build a watertight solid: the depth-mapped front surface, a flat back
    plane on the same (x, y) grid, and side walls stitching their shared
    boundary together."""
    height, width = lightness.shape
    n = width * height
    trans_x = -width / (2 * dpm)
    trans_y = -height / (2 * dpm)

    ys, xs = np.mgrid[0:height, 0:width]
    vx = np.round(xs / dpm + trans_x, 4)
    vy = np.round(-(ys / dpm + trans_y), 4)
    vz_front = np.round(lightness * depth_range / dpm, 4)
    back_z = round(float(vz_front.min()) - base_thickness / dpm, 4)
    vz_back = np.full_like(vz_front, back_z)

    front_verts = np.stack([vx, vy, vz_front], axis=-1).reshape(-1, 3)
    back_verts = np.stack([vx, vy, vz_back], axis=-1).reshape(-1, 3)
    verts = np.concatenate([front_verts, back_verts], axis=0)

    def idx(row, col, offset=0):
        return row * width + col + 1 + offset

    # Front surface, facing +z (unchanged from the original mesh).
    yy, xx = np.mgrid[0:height - 1, 0:width - 1]
    v = idx(yy, xx)
    front_f1 = np.stack([v, v + width + 1, v + 1], axis=-1).reshape(-1, 3)
    front_f2 = np.stack([v, v + width, v + width + 1], axis=-1).reshape(-1, 3)

    # Back plane, same topology, reversed winding so it faces -z.
    vb = idx(yy, xx, offset=n)
    back_f1 = np.stack([vb, vb + 1, vb + width + 1], axis=-1).reshape(-1, 3)
    back_f2 = np.stack([vb, vb + width + 1, vb + width], axis=-1).reshape(-1, 3)

    # Side walls along the four boundary edges, wound to face outward.
    c = np.arange(width - 1)
    top1 = np.stack([idx(0, c), idx(0, c + 1), idx(0, c + 1, n)], axis=-1)
    top2 = np.stack([idx(0, c), idx(0, c + 1, n), idx(0, c, n)], axis=-1)

    bottom1 = np.stack([idx(height - 1, c + 1), idx(height - 1, c), idx(height - 1, c, n)], axis=-1)
    bottom2 = np.stack([idx(height - 1, c + 1), idx(height - 1, c, n), idx(height - 1, c + 1, n)], axis=-1)

    r = np.arange(height - 1)
    right1 = np.stack([idx(r, width - 1), idx(r + 1, width - 1), idx(r + 1, width - 1, n)], axis=-1)
    right2 = np.stack([idx(r, width - 1), idx(r + 1, width - 1, n), idx(r, width - 1, n)], axis=-1)

    left1 = np.stack([idx(r + 1, 0), idx(r, 0), idx(r, 0, n)], axis=-1)
    left2 = np.stack([idx(r + 1, 0), idx(r, 0, n), idx(r + 1, 0, n)], axis=-1)

    faces = np.concatenate([
        front_f1, front_f2,
        back_f1, back_f2,
        top1, top2, bottom1, bottom2,
        right1, right2, left1, left2,
    ], axis=0)

    return verts, faces


def write_obj(path: str, verts: np.ndarray, faces: np.ndarray) -> None:
    with open(path, "w") as f:
        f.write("# Generated by depthmap_to_stl.py\n")
        f.write("# Ported from the Digital Epigraphy and Archaeology project.\n")
        np.savetxt(f, verts, fmt="v %.4f %.4f %.4f")
        np.savetxt(f, faces, fmt="f %d %d %d")
        f.write("# End of file.\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", default="rosetta1.png", help="source image path")
    parser.add_argument("--output", default="rosetta1.obj", help="output OBJ path")
    parser.add_argument("--x", type=int, required=True, help="region left (px)")
    parser.add_argument("--y", type=int, required=True, help="region top (px)")
    parser.add_argument("--width", type=int, required=True, help="region width (px)")
    parser.add_argument("--height", type=int, required=True, help="region height (px)")
    parser.add_argument("--dpm", type=float, required=True, help="dots per metre")
    parser.add_argument("--depth-range", type=float, required=True,
                         help="Z depth range in metres for a full-white pixel")
    parser.add_argument("--base-thickness", default=35, type=float,
                         help="flat slab thickness behind the lowest surface point, "
                              "same units as --depth-range (divided by dpm)")
    args = parser.parse_args()

    im = Image.open(args.image).convert("RGB")
    box = (args.x, args.y, args.x + args.width, args.y + args.height)
    region = im.crop(box)

    lightness = rgb_to_hsl_lightness(np.array(region))
    verts, faces = build_mesh(lightness, args.dpm, args.depth_range, args.base_thickness)
    write_obj(args.output, verts, faces)

    print(f"Wrote {args.output}: {len(verts)} vertices, {len(faces)} faces")


if __name__ == "__main__":
    main()
